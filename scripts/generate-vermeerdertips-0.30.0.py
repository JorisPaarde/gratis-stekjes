def soort(
    slug: str,
    naam: str,
    latijn: str,
    *,
    categorie: str,
    waarom: str,
    methode: str,
    wanneer: str,
    welk_hout: str,
    lengte_snit: str,
    water_grond: str,
    hulpmiddel: str,
    kans: str,
    klaar: str,
    bronnen: str,
    kort: str,
    licht: str,
    water: str,
    verwanten: list[str] | None = None,
    waarschuwing: str = "",
    ervaringen: str = "",
    seo_naam: str | None = None,
    seo_werkwoord: str | None = None,
    inhoud: list | None = None,
) -> dict:
    row = {
        "slug": slug,
        "naam": naam,
        "latijn": latijn,
        "categorie": categorie,
        "waarom": waarom,
        "methode": methode,
        "wanneer": wanneer,
        "welk_hout": welk_hout,
        "lengte_snit": lengte_snit,
        "water_grond": water_grond,
        "licht": licht,
        "water": water,
        "hulpmiddel": hulpmiddel,
        "kans": kans,
        "klaar": klaar,
        "verwanten": verwanten or [],
        "waarschuwing": waarschuwing,
        "ervaringen": ervaringen,
        "bronnen": bronnen,
        "kort": kort,
    }
    if seo_naam:
        row["seo_naam"] = seo_naam
    if seo_werkwoord:
        row["seo_werkwoord"] = seo_werkwoord
    if inhoud:
        row["inhoud"] = inhoud
    return row


