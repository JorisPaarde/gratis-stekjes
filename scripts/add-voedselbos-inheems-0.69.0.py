# Alias tip slug used in verwanten that maps to existing tip
ALIAS_SLUGS = {
    "wilde-marjolein": "oregano",
    "boerenkool": "eeuwig-moes",  # no tip; drop later if missing
    "spinazie": None,
    "snijbiet": None,
    "cranberry": None,
    "mierik": "mierikswortel",
    "stokroos": None,
}


def tip_fields(p: dict) -> dict:
    row = {
        "slug": p["slug"],
        "naam": p["naam"],
        "latijn": p["latijn"],
        "categorie": p["categorie"],
        "tags": p["tags"],
        "waarom": p["waarom"],
        "methode": p["methode"],
        "wanneer": p["wanneer"],
        "welk_hout": p["welk_hout"],
        "lengte_snit": p["lengte_snit"],
        "water_grond": p["water_grond"],
        "licht": p["licht"],
        "water": p["water"],
        "hulpmiddel": p["hulpmiddel"],
        "kans": p["kans"],
        "klaar": p["klaar"],
        "verwanten": [],
        "waarschuwing": p.get("waarschuwing", ""),
        "ervaringen": "",
        "bronnen": p["bronnen"],
        "kort": p["kort"],
    }
    if p.get("seo_werkwoord"):
        row["seo_werkwoord"] = p["seo_werkwoord"]
    # resolve verwanten to existing/new slugs only
    known = {x["slug"] for x in PLANTS}
    # plus will fill with existing stektips later
    row["_verwanten_raw"] = p.get("verwanten", [])
    return row


def main() -> None:
    stektips_path = ROOT / "data" / "stektips.json"
    soorten_dir = ROOT / "soorten"
    planten_path = ROOT / "data" / "plantensoorten.json"

    stektips = json.loads(stektips_path.read_text(encoding="utf-8"))
    existing_slugs = {s["slug"] for s in stektips["soorten"]}
    new_plants = [p for p in PLANTS if p["slug"] not in existing_slugs]
    skipped = [p["slug"] for p in PLANTS if p["slug"] in existing_slugs]
    print(f"new tips: {len(new_plants)}, already present in stektips: {skipped}")

    all_tip_slugs = existing_slugs | {p["slug"] for p in new_plants}

    tip_rows = []
    for p in new_plants:
        row = tip_fields(p)
        verw = []
        for v in row.pop("_verwanten_raw"):
            v2 = ALIAS_SLUGS.get(v, v)
            if v2 and v2 in all_tip_slugs:
                verw.append(v2)
        row["verwanten"] = verw[:4]
        tip_rows.append(row)
        (soorten_dir / f"{p['slug']}.json").write_text(
            json.dumps(row, ensure_ascii=False, indent=4) + "\n", encoding="utf-8"
        )

    stektips["soorten"].extend(tip_rows)
    stektips["soorten"].sort(key=lambda s: s["naam"].casefold())
    stektips_path.write_text(
        json.dumps(stektips, ensure_ascii=False, indent=4) + "\n", encoding="utf-8"
    )

    # Sync soorten/*.json for new ones already written; also rewrite from stektips for consistency
    by_slug = {s["slug"]: s for s in stektips["soorten"]}
    for p in new_plants:
        (soorten_dir / f"{p['slug']}.json").write_text(
            json.dumps(by_slug[p["slug"]], ensure_ascii=False, indent=4) + "\n",
            encoding="utf-8",
        )

    planten = json.loads(planten_path.read_text(encoding="utf-8"))
    items = planten["soorten"]
    by_id = {i["id"]: i for i in items}
    max_id = max(i["id"] for i in items)

    # Tag oregano as inheems too (wilde marjolein synonym)
    for i in items:
        if i.get("slug") == "oregano":
            tags = list(i.get("tags") or [])
            if "inheems" not in tags:
                tags.append("inheems")
            if "voedselbos" not in tags:
                tags.append("voedselbos")
            i["tags"] = tags

    for p in new_plants:
        eid = p.get("existing_id")
        if eid and eid in by_id:
            row = by_id[eid]
            row["slug"] = p["slug"]
            row["latijn"] = p.get("fix_latijn", p["latijn"])
            if p.get("rename_naam"):
                row["naam"] = p["rename_naam"]
            if p.get("fix_synoniemen"):
                row["synoniemen"] = p["fix_synoniemen"]
            else:
                syn = list(row.get("synoniemen") or [])
                for s in p.get("synoniemen", []):
                    if s not in syn and s != row["naam"]:
                        syn.append(s)
                row["synoniemen"] = syn
            tags = list(row.get("tags") or [])
            for t in p["tags"]:
                if t not in tags:
                    tags.append(t)
            row["tags"] = tags
            row["zichtbaar"] = True
            if p.get("plantensoort_categorie"):
                row["categorie"] = p["plantensoort_categorie"]
        else:
            max_id += 1
            items.append(
                {
                    "id": max_id,
                    "naam": p["naam"],
                    "latijn": p["latijn"],
                    "synoniemen": [s for s in p.get("synoniemen", []) if s != p["naam"]],
                    "slug": p["slug"],
                    "categorie": p.get("plantensoort_categorie", "tuin"),
                    "zichtbaar": True,
                    "tags": p["tags"],
                }
            )

    # recount meta
    with_slug = sum(1 for i in items if i.get("slug"))
    zichtbaar = sum(1 for i in items if i.get("zichtbaar", True))
    verborgen = len(items) - zichtbaar
    vb = sum(1 for i in items if "voedselbos" in (i.get("tags") or []))
    ih = sum(1 for i in items if "inheems" in (i.get("tags") or []))
    planten["meta"] = {
        **planten.get("meta", {}),
        "aantal": len(items),
        "met_stektips_pagina": with_slug,
        "zichtbaar": zichtbaar,
        "verborgen": verborgen,
        "voedselbos": vb,
        "inheems": ih,
    }
    planten["soorten"] = items
    planten_path.write_text(
        json.dumps(planten, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    manifest = ROOT / "storage" / "app" / "nieuwe-soorten-0.69.0.json"
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(
        json.dumps(
            {
                "slugs": [p["slug"] for p in new_plants],
                "voedselbos": [p["slug"] for p in new_plants if "voedselbos" in p["tags"]],
                "inheems": [p["slug"] for p in new_plants if "inheems" in p["tags"]],
                "latijn": {p["slug"]: p["latijn"] for p in new_plants},
                "namen": {p["slug"]: p["naam"] for p in new_plants},
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(new_plants)} tip pages; plantensoorten met_stektips={with_slug}")
    print("voedselbos new:", len([p for p in new_plants if 'voedselbos' in p['tags']]))
    print("inheems new:", len([p for p in new_plants if 'inheems' in p['tags']]))


if __name__ == "__main__":
    main()
